logger = logging.getLogger(__name__)


def render_markdown(md_content: str, metadata: dict = None) -> str:
    """
    Clean up and standardize the markdown protocol.
    Adds a header with generation metadata.
    """
    metadata = metadata or {}
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    session_id = metadata.get("session_id", "unknown")
    task_query = metadata.get("task_query", "N/A")
    validation_approved = metadata.get(
        "validation_approved",
        metadata.get("critic_approved"),
    )
    validation_issues = metadata.get(
        "validation_issues",
        metadata.get("critic_issues") or [],
    )
    include_review_metadata = bool(metadata.get("include_review_metadata"))

    title = "# Experimental Protocol"
    header_lines = [
        title,
        "**Generated by:** Bio-MARS AutoProtocol",
        f"**Date:** {timestamp}",
        f"**Session ID:** {session_id}",
        f"**Task:** {task_query}",
    ]

    if include_review_metadata:
        if validation_approved is True:
            status_label = "APPROVED"
            validation_approved_str = "True"
        elif validation_approved is False:
            status_label = "DRAFT/UNAPPROVED"
            validation_approved_str = "False"
        else:
            status_label = "DRAFT"
            validation_approved_str = "Unknown"

        header_lines[0] = f"{title} ({status_label})"
        header_lines.append(
            f"**Integrity Validation Passed:** {validation_approved_str}"
        )
        if validation_issues:
            header_lines.append("**Integrity Issues:**")
            for issue in validation_issues:
                header_lines.append(f"- {issue}")

    header_lines.append("")
    header_lines.append("---")
    header_lines.append("")

    header = "\n".join(header_lines) + "\n"
    return header + md_content


def export_pdf(md_path: str, pdf_path: str) -> None:
    """
    Export markdown file to PDF using available backends:
    1. Pandoc (CLI)
    2. WeasyPrint (Python lib)
    3. ReportLab (Python lib, fallback)
    """

    # Check env override
    engine = os.getenv("PROTOCOL_PDF_ENGINE", "auto")

    if engine == "pandoc" or (engine == "auto" and shutil.which("pandoc")):
        try:
            _export_pandoc(md_path, pdf_path)
            return
        except Exception as e:
            logger.warning(f"Pandoc export failed: {e}. Trying fallbacks.")

    if engine == "weasyprint" or (engine == "auto"):
        try:
            _export_weasyprint(md_path, pdf_path)
            return
        except ImportError:
            if engine == "weasyprint":
                logger.warning("WeasyPrint not installed.")
        except Exception as e:
            logger.warning(f"WeasyPrint export failed: {e}. Trying fallbacks.")

    # Fallback to ReportLab (or simple text wrap if even that fails)
    try:
        _export_reportlab(md_path, pdf_path)
    except Exception as e:
        logger.error(f"All PDF export methods failed. Last error: {e}")
        raise


def _export_pandoc(md_path: str, pdf_path: str):
    logger.info("Exporting PDF via Pandoc...")
    # pandoc input.md -o output.pdf --pdf-engine=xelatex (if avail) or wkhtmltopdf
    # We'll stick to default pdf-engine usually (pdflatex)
    cmd = ["pandoc", md_path, "-o", pdf_path]
    subprocess.run(cmd, check=True, capture_output=True)
    logger.info(f"PDF saved to {pdf_path}")


def _markdown_to_html(text: str) -> str:
    """Render protocol Markdown with the repository's declared parser."""

    from markdown_it import MarkdownIt

    script_maps = [
        ("₀₁₂₃₄₅₆₇₈₉", "sub"),
        ("⁰¹²³⁴⁵⁶⁷⁸⁹", "sup"),
    ]
    normalized_text = str(text or "")
    for characters, tag in script_maps:
        translation = str.maketrans(
            characters,
            "0123456789",
        )
        normalized_text = re.sub(
            f"[{characters}]+",
            lambda match, html_tag=tag, table=translation: (
                f"<{html_tag}>"
                f"{match.group(0).translate(table)}"
                f"</{html_tag}>"
            ),
            normalized_text,
        )

    return (
        MarkdownIt(
            "commonmark",
            {
                "breaks": True,
                "html": True,
                "linkify": False,
            },
        )
        .enable("table")
        .render(normalized_text)
    )


