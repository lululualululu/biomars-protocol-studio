def _reportlab_list(tag, styles, available_width, level=0):
    from bs4 import NavigableString
    from reportlab.platypus import ListFlowable, ListItem, Paragraph

    items = []
    for item in tag.find_all("li", recursive=False):
        flowables = []
        inline_nodes = []

        def flush_inline():
            if not inline_nodes:
                return
            markup = "".join(
                _reportlab_inline_markup(node)
                for node in inline_nodes
            ).strip()
            inline_nodes.clear()
            if markup:
                flowables.append(Paragraph(markup, styles["list"]))

        for child in item.contents:
            child_name = str(getattr(child, "name", "") or "").lower()
            if child_name in {"ul", "ol"}:
                flush_inline()
                flowables.append(
                    _reportlab_list(
                        child,
                        styles,
                        available_width,
                        level=level + 1,
                    )
                )
            elif child_name == "p":
                flush_inline()
                markup = _reportlab_inline_markup(child).strip()
                if markup:
                    flowables.append(Paragraph(markup, styles["list"]))
            elif isinstance(child, NavigableString) or child_name:
                inline_nodes.append(child)
        flush_inline()
        if not flowables:
            continue
        items.append(
            ListItem(
                flowables,
                leftIndent=0,
                spaceAfter=2,
            )
        )

    ordered = str(tag.name).lower() == "ol"
    try:
        start = int(tag.get("start") or 1)
    except (TypeError, ValueError):
        start = 1
    return ListFlowable(
        items,
        bulletType="1" if ordered else "bullet",
        start=start if ordered else None,
        leftIndent=max(4, 14 - min(level, 1) * 10),
        rightIndent=0,
        bulletFontName="Helvetica",
        bulletFontSize=8,
        bulletOffsetY=1,
        spaceBefore=1,
        spaceAfter=5,
    )


def _reportlab_table(tag, styles, available_width):
    from reportlab.lib import colors
    from reportlab.platypus import Paragraph, Table, TableStyle

    rows = []
    header_rows = 0
    for row in tag.find_all("tr"):
        cells = row.find_all(["th", "td"], recursive=False)
        if not cells:
            continue
        if all(str(cell.name).lower() == "th" for cell in cells):
            header_rows += 1
        rows.append(
            [
                Paragraph(
                    _reportlab_inline_markup(cell),
                    (
                        styles["table_header"]
                        if str(cell.name).lower() == "th"
                        else styles["table"]
                    ),
                )
                for cell in cells
            ]
        )
    if not rows:
        return None

    column_count = max(len(row) for row in rows)
    for row in rows:
        row.extend([""] * (column_count - len(row)))
    table = Table(
        rows,
        colWidths=[available_width / column_count] * column_count,
        repeatRows=header_rows,
        hAlign="LEFT",
    )
    commands = [
        ("GRID", (0, 0), (-1, -1), 0.45, colors.HexColor("#cfd8df")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    if header_rows:
        commands.append(
            (
                "BACKGROUND",
                (0, 0),
                (-1, header_rows - 1),
                colors.HexColor("#eaf0f4"),
            )
        )
    table.setStyle(TableStyle(commands))
    return table


def _reportlab_story(html_text: str, styles, available_width):
    from bs4 import BeautifulSoup, Comment, NavigableString
    from reportlab.lib.colors import HexColor
    from reportlab.platypus import (
        HRFlowable,
        Paragraph,
        Spacer,
        XPreformatted,
    )

    soup = BeautifulSoup(html_text, "html.parser")
    story = []

    for node in soup.contents:
        if isinstance(node, Comment):
            continue
        if isinstance(node, NavigableString):
            text = str(node).strip()
            if text:
                story.append(Paragraph(text, styles["body"]))
            continue

        name = str(getattr(node, "name", "") or "").lower()
        if name in {"h1", "h2", "h3", "h4", "h5", "h6"}:
            style_name = name if name in styles else "h4"
            story.append(
                Paragraph(
                    _reportlab_inline_markup(node),
                    styles[style_name],
                )
            )
        elif name == "p":
            plain = node.get_text(" ", strip=True)
            style = (
                styles["metadata"]
                if plain.startswith("Generated by:")
                else (
                    styles["evidence"]
                    if plain.startswith("Evidence:")
                    else styles["body"]
                )
            )
            story.append(
                Paragraph(
                    _reportlab_inline_markup(node),
                    style,
                )
            )
        elif name in {"ul", "ol"}:
            story.append(
                _reportlab_list(
                    node,
                    styles,
                    available_width,
                )
            )
        elif name == "table":
            table = _reportlab_table(node, styles, available_width)
            if table is not None:
                story.extend([table, Spacer(1, 7)])
        elif name == "blockquote":
            story.append(
                Paragraph(
                    _reportlab_inline_markup(node),
                    styles["quote"],
                )
            )
        elif name == "pre":
            story.append(
                XPreformatted(
                    node.get_text(),
                    styles["code"],
                )
            )
        elif name == "hr":
            story.append(
                HRFlowable(
                    width="100%",
                    thickness=0.6,
                    color=HexColor("#d8e0e7"),
                    spaceBefore=4,
                    spaceAfter=7,
                )
            )
        else:
            markup = _reportlab_inline_markup(node).strip()
            if markup:
                story.append(Paragraph(markup, styles["body"]))
    return story


def _export_reportlab(md_path: str, pdf_path: str):
    logger.info("Exporting PDF via ReportLab (Fallback)...")
    from reportlab.lib.colors import HexColor
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate

    with open(md_path, "r", encoding="utf-8") as f:
        text = f.read()

    doc = SimpleDocTemplate(
        pdf_path,
        pagesize=A4,
        leftMargin=17 * mm,
        rightMargin=17 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
        title="Bio-MARS Experimental Protocol",
        author="Bio-MARS AutoProtocol",
        subject="Generated experimental protocol",
    )
    styles = _reportlab_styles()
    story = _reportlab_story(
        _markdown_to_html(text),
        styles,
        A4[0] - doc.leftMargin - doc.rightMargin,
    )
    if not story:
        raise ValueError("Protocol Markdown produced no renderable PDF content")

    def draw_footer(canvas, document):
        canvas.saveState()
        canvas.setStrokeColor(HexColor("#d8e0e7"))
        canvas.setLineWidth(0.4)
        canvas.line(
            document.leftMargin,
            12 * mm,
            A4[0] - document.rightMargin,
            12 * mm,
        )
        canvas.setFillColor(HexColor("#6b7280"))
        canvas.setFont("Helvetica", 7.5)
        canvas.drawString(
            document.leftMargin,
            8.2 * mm,
            "Bio-MARS AutoProtocol",
        )
        canvas.drawRightString(
            A4[0] - document.rightMargin,
            8.2 * mm,
            f"Page {document.page}",
        )
        canvas.restoreState()

    doc.build(
        story,
        onFirstPage=draw_footer,
        onLaterPages=draw_footer,
    )
    logger.info(f"PDF saved to {pdf_path}")
