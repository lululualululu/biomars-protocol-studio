def _reportlab_inline_markup(node) -> str:
    """Convert inline HTML to the small markup subset ReportLab supports."""

    import xml.sax.saxutils as saxutils
    from bs4 import Comment, NavigableString

    if isinstance(node, Comment):
        return ""
    if isinstance(node, NavigableString):
        return saxutils.escape(str(node))

    name = str(getattr(node, "name", "") or "").lower()
    if name == "br":
        return "<br/>"
    if name == "img":
        return saxutils.escape(str(node.get("alt") or ""))

    content = "".join(
        _reportlab_inline_markup(child)
        for child in getattr(node, "children", [])
    )
    if name in {"strong", "b"}:
        return f"<b>{content}</b>"
    if name in {"em", "i"}:
        return f"<i>{content}</i>"
    if name == "code":
        return f'<font name="Courier">{content}</font>'
    if name in {"sup", "sub", "u"}:
        return f"<{name}>{content}</{name}>"
    if name == "a":
        href = str(node.get("href") or "").strip()
        if href:
            return (
                f'<link href={saxutils.quoteattr(href)} '
                f'color="#1f5c99">{content}</link>'
            )
    return content


